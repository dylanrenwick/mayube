PRAGMA foreign_keys = ON;

CREATE TABLE IF NOT EXISTS `posts` (
	`id` INTEGER PRIMARY KEY AUTOINCREMENT CHECK (`id` BETWEEN 0 AND 4294967295),
	`user_id` INTEGER NOT NULL CHECK (typeof(`user_id`) = 'integer' AND `user_id` BETWEEN 0 AND 4294967295),
	`title` TEXT COLLATE NOCASE NOT NULL,
	`text` TEXT COLLATE NOCASE NOT NULL,
	`tags` TEXT COLLATE NOCASE DEFAULT '',
	`categories` TEXT COLLATE NOCASE DEFAULT '',
	`active` INTEGER DEFAULT 0 CHECK (`active` IN (0, 1)),
	`created_at` TEXT DEFAULT CURRENT_TIMESTAMP,
	`modified_at` TEXT DEFAULT CURRENT_TIMESTAMP,
	CONSTRAINT `fk_post_author`
		FOREIGN KEY (`user_id`) REFERENCES `users` (`id`)
		ON UPDATE RESTRICT
);
